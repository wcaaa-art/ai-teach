// 掌握情况文案：优先用专题的动作级文案，没有就用档位通用句。
export function describeMastery({ chapterName = '', mastery = 0 } = {}) {
  const level = Math.max(0, Math.min(3, Number(mastery) || 0))
  const table = ACTION_LEVEL[chapterName]
  if (table && table[level]) return table[level]
  return LEVEL_FALLBACK[level]
}
