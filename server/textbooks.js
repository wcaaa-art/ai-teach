// 为人教版和统编版保留原有的跨版本专题，避免已保存的掌握度与计划 id 断裂。
const CROSS_EDITION_SLUGS = new Set(['rjb', 'tb'])

export function listTextbookEditions(subject = '') {
  return TEXTBOOK_EDITIONS[subject] || [{ edition: '人教版', slug: 'rjb', note: '暂按人教版单元顺序提供。' }]
}

export function resolveTextbookEdition(subject = '', edition = '') {
  const editions = listTextbookEditions(subject)
  const matched = editions.find(item => item.edition === edition)
  return matched || editions[0]
}

export function textbookEditionChapters(grade = '', subject = '', edition = '') {
  const resolved = resolveTextbookEdition(subject, edition)
  if (CROSS_EDITION_SLUGS.has(resolved.slug)) return null
  const units = editionUnits[subject]?.[resolved.edition]?.[grade]
  if (!units || !units.length) return null
  return { edition: resolved.edition, slug: resolved.slug, note: resolved.note, units }
}

export function listTextbookEditionMap(subjects = []) {
  return Object.fromEntries(subjects.map(subject => [subject, listTextbookEditions(subject)]))
}
